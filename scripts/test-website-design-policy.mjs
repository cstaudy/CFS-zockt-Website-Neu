import assert from "node:assert/strict";
import {checkDesignMedia as media,checkDesignRevision as revision,checkDesignMediaDeletion as deletion} from "../src/website-design-policy.js";
const a={id:"a",accountId:"owner",mimeType:"image/png",validated:true,deleted:false,publicApproved:false};
assert.equal(media(null,null,"owner",true).ok,true);
assert.equal(media("a",a,"owner").ok,true);
assert.equal(media("a",a,"other").ok,false);
assert.equal(media("b",a,"owner").ok,false);
assert.equal(media("a",null,"owner").ok,false);
assert.equal(media("a",a,"owner",true).ok,false);
assert.equal(media("a",{...a,publicApproved:true},"owner",true).ok,true);
for(const patch of [{deleted:true},{validated:false},{mimeType:"image/svg+xml"},{deleted:undefined}]) assert.equal(media("a",{...a,...patch},"owner").ok,false);
assert.equal(revision(0,0).ok,true);
assert.equal(revision(3,4).error,"REVISION_CONFLICT");
for(const v of [-1,1.5,"3",Infinity,Number.MAX_SAFE_INTEGER+1]) assert.equal(revision(v,3).ok,false);
assert.equal(deletion("a",[{backgroundAssetId:"a"}]).error,"MEDIA_IN_USE");
assert.equal(deletion("a",[{backgroundAssetId:null}]).ok,true);
assert.equal(deletion("a",null).ok,false);
assert.equal(deletion("a",[{}]).ok,false);
console.log("Website design policy passed");
