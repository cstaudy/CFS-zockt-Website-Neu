import assert from "node:assert/strict";
import { normalizePublisherPreview, previewPublisher } from "../src/publisher-preview.js";
const id="11111111-1111-4111-8111-111111111111", account="22222222-2222-4222-8222-222222222222";
const body={media_id:id,targets:["tiktok","youtube_shorts","instagram_reels","facebook_reels"],title:" Highlight ",description:"Text",captions:true,brand_style:"gaming"};
assert.equal(normalizePublisherPreview(body).title,"Highlight");
for (const change of [{media_id:"https://evil.invalid"},{targets:[]},{targets:["tiktok","tiktok"]},{targets:["kick"]},{targets:["youtube_shorts","youtube_video"]},{title:" "},{title:"a".repeat(101)},{captions:"yes"},{brand_style:"<script>"},{publish:true},{account_id:account},{description:42},{targets:["__proto__"]}])
  assert.equal(normalizePublisherPreview({...body,...change}).status,400);
const calls=[];
const db={async query(sql,values){calls.push({sql,values});return {rows:sql.includes("from user_media")?[{id,mime_type:"video/mp4",size_bytes:"1024",duration_ms:20000,storage_path:"private"}]:[{provider:"tiktok",scope:"user.info.basic,video.publish",expires_at:"2027-01-01",access_token:"secret"}]};}};
const result=await previewPublisher(db,account,body,{tiktok:true},Date.parse("2026-11-28"));
assert.equal(result.can_publish,false);
assert.equal(result.job_created,false);
assert.equal(result.targets.length,4);
assert(result.targets.every(t=>t.state==="blocked"&&!t.can_publish));
assert.equal(result.targets[0].width,1080);
assert(result.targets[0].blockers.includes("TIKTOK_CREATOR_INFO_REQUIRED"));
assert(!result.targets[0].blockers.includes("PUBLISH_SCOPE_REQUIRED"));
assert(result.targets[1].blockers.includes("ACCOUNT_CONNECTION_REQUIRED"));
assert.doesNotMatch(JSON.stringify(result),/private|secret|storage_path/);
assert.equal(calls.length,2);
assert.deepEqual(calls[0].values,[id,account]);
assert.deepEqual(calls[1].values,[account]);
assert(calls.every(c=>/^select /i.test(c.sql)));
const miss={async query(){return {rows:[]};}};
assert.equal((await previewPublisher(miss,account,body)).status,404);
assert.equal((await previewPublisher(db,"",body)).status,401);
assert.equal((await previewPublisher(db,account,{...body,publish:true})).status,400);
assert.equal(calls.length,2);
console.log("Publisher preview: strict inputs, owned media, target profiles, blockers and no side effects.");
