import assert from "node:assert/strict";
import { buildPublishingDraft, comparePublishingIntent, reducePublishingTarget } from "../src/publisher-job-contract.js";
const account="22222222-2222-4222-8222-222222222222", other="33333333-3333-4333-8333-333333333333";
const request="44444444-4444-4444-8444-444444444444";
const a1="55555555-5555-4555-8555-555555555555", a2="66666666-6666-4666-8666-666666666666", a3="77777777-7777-4777-8777-777777777777";
const body={media_id:"11111111-1111-4111-8111-111111111111",targets:["tiktok","instagram_reels"],title:"Highlight",description:"Text",captions:true,brand_style:"gaming"};
const job=buildPublishingDraft(account,request,body);
assert.equal(job.mode,"contract_only");
assert.equal(job.targets.length,2);
assert.notEqual(job.targets[0].key,job.targets[1].key);
assert.equal(comparePublishingIntent(job,buildPublishingDraft(account,request,{...body,targets:[...body.targets].reverse()})),"same_intent");
assert.equal(comparePublishingIntent(job,buildPublishingDraft(account,request,{...body,title:"Different"})),"conflict");
assert.equal(comparePublishingIntent(job,buildPublishingDraft(other,request,body)),"different_intent");
assert.equal(comparePublishingIntent(job,buildPublishingDraft(account,a1,body)),"different_intent");
assert.equal(comparePublishingIntent(job,{}),"invalid");
assert.equal(buildPublishingDraft("bad",request,body).error,"INVALID_PUBLISHING_IDENTITY");
assert.equal(buildPublishingDraft(account,request,{...body,publish:true}).error,"INVALID_PUBLISHER_PREVIEW");
const t=job.targets[0];
const ev=(current,type,extra={})=>reducePublishingTarget(current,{type,expected_revision:current.revision,...extra});
const denied=(current,type,extra={})=>assert.equal(ev(current,type,extra).error,"PUBLISHING_TRANSITION_DENIED");
denied(t,"begin_attempt",{attempt_id:a1});
let q=ev(t,"authorize");
assert.equal(q.state,"queued");
assert.equal(reducePublishingTarget(q,{type:"cancel",expected_revision:0}).error,"PUBLISHING_REVISION_CONFLICT");
let preparing=ev(q,"begin_attempt",{attempt_id:a1});
assert.equal(preparing.attempts,1);
denied(preparing,"provider_accepted",{attempt_id:a1,provider_ref:"id-1"});
denied(preparing,"submit_started",{attempt_id:a2});
let submitting=ev(preparing,"submit_started",{attempt_id:a1});
denied(submitting,"cancel");
denied(submitting,"pre_submit_failure",{attempt_id:a1});
let unknown=ev(submitting,"submission_unknown",{attempt_id:a1});
assert.equal(unknown.state,"reconcile_required");
denied(unknown,"begin_attempt",{attempt_id:a2});
denied(unknown,"cancel");
denied(unknown,"provider_confirmed_absent",{attempt_id:a2});
let accepted=ev(unknown,"provider_accepted",{attempt_id:a1,provider_ref:"id-1"});
assert.equal(accepted.state,"submitted");
denied(accepted,"begin_attempt",{attempt_id:a2});
denied(accepted,"provider_published",{provider_ref:"wrong"});
const published=ev(accepted,"provider_published",{provider_ref:"id-1"});
assert.equal(published.state,"published");
denied(published,"authorize");
denied(published,"cancel");
assert.equal(ev(accepted,"provider_failed",{provider_ref:"id-1"}).state,"failed");
denied(unknown,"provider_accepted",{attempt_id:a1,provider_ref:"https://example.invalid/token"});
let retry=ev(unknown,"provider_confirmed_absent",{attempt_id:a1});
assert.equal(retry.state,"retryable");
denied(retry,"begin_attempt",{attempt_id:a1});
let second=ev(retry,"begin_attempt",{attempt_id:a2});
assert.equal(second.attempts,2);
retry=ev(second,"pre_submit_failure",{attempt_id:a2});
let third=ev(retry,"begin_attempt",{attempt_id:a3});
assert.equal(third.attempts,3);
assert.equal(ev(third,"pre_submit_failure",{attempt_id:a3}).state,"failed");
assert.equal(ev(q,"cancel").state,"canceled");
assert.equal(ev(t,"authorize",{token:"never-accept"}).error,"INVALID_PUBLISHING_EVENT");
assert.equal(job.targets[1].state,"draft","another target stays independent");
assert.equal(t.state,"draft","reducer must not mutate input");
assert.doesNotMatch(JSON.stringify(job), /Highlight|account_id|storage_path|access_token/);
console.log("Publishing job contract: idempotency, revision conflicts, independent targets, reconciliation, retry ceiling, terminal and cancel guards.");
