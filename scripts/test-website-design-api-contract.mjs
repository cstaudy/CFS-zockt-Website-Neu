import assert from "node:assert/strict";
import {initialDesignState} from "../src/website-design-state.js";
import {prepareDesignMutation as mutate,publicDesignResponse as read} from "../src/website-design-api-contract.js";
const state=initialDesignState(),cmd={type:"save",expectedRevision:0,design:{shade:40}},ctx={accountId:"owner",isAdmin:true,elevated:true};
assert.equal(mutate(state,cmd,{}).status,401);
assert.equal(mutate(state,cmd,{accountId:"owner"}).status,403);
assert.equal(mutate(state,cmd,{...ctx,elevated:false}).status,428);
assert.equal(mutate(state,{...cmd,elevated:true},{...ctx,elevated:false}).status,428);
assert.equal(mutate(state,{...cmd,accountId:"other"},ctx).status,400);
assert.equal(mutate(state,{...cmd,type:"__proto__"},ctx).status,400);
assert.equal(mutate(state,{...cmd,expectedRevision:1},ctx).status,409);
assert.equal(mutate(state,{type:"restore",expectedRevision:0,sourceRevision:9},ctx).status,404);
const saved=mutate(state,cmd,ctx);
assert.equal(saved.status,200);
assert.equal(saved.candidate.draft.shade,40);
assert.equal(state.revision,0);
assert.equal(saved.expectedRevision,0);
assert.deepEqual(read(saved.candidate,{}).body,{design:null});
const published=mutate(saved.candidate,{type:"publish",expectedRevision:1},ctx);
assert.equal(read(published.candidate,{}).body.design.shade,40);
assert.equal(read(published.candidate,{}).headers["cache-control"],"no-store");
console.log("Design API contract passed");
