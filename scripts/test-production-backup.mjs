import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";

test("production backup script enforces protected storage, TLS and restore comparison", async () => {
  const source = await readFile(new URL("./production-pg-backup.ps1", import.meta.url), "utf8");
  const restoreValidator = await readFile(new URL("./validate-neon-restore.mjs", import.meta.url), "utf8");
  assert.match(source, /Get-BitLockerVolume/);
  assert.match(source, /OneDrive/);
  assert.match(source, /PGSSLMODE\s*=\s*"verify-full"/);
  assert.match(source, /PGSSLROOTCERT\s*=\s*\$script:RootCertificate/);
  assert.match(source, /function Assert-RootCertificate/);
  assert.match(source, /96BCEC06264976F37460779ACF28C5A7CFE8A3C0AAE11A8FFCEE05C0BDDF08C6/);
  assert.match(source, /69729B8E15A86EFC177A57AFB7171DFC64ADD28C2FCA8CF1507E34453CCB1470/);
  assert.match(source, /PSNativeCommandUseErrorActionPreference/);
  assert.match(source, /function Assert-NetworkReachability/);
  assert.match(source, /function Write-Diagnostic/);
  assert.match(source, /function ConvertTo-SafeDiagnostic/);
  assert.match(source, /PGSERVICEFILE/);
  assert.match(source, /\[string\]\$HostName/);
  assert.match(source, /\[ValidateSet\("Render", "Neon"\)\]/);
  assert.match(source, /Read-DatabaseCredentials \$sourceLabel \$Database \$HostName \$Port \$User/);
  assert.match(source, /\[string\]\$RootCertificatePath/);
  assert.match(source, /\[switch\]\$NativePasswordPrompt/);
  assert.match(source, /\$script:NativePasswordPrompt/);
  assert.match(source, /"--password"/);
  assert.match(source, /Remove-Item Env:PGPASSWORD/);
  assert.match(source, /if \(\$script:NativePasswordPrompt\) \{\s*\$password = \$null/);
  assert.match(source, /\[Alias\("FetchRenderRoots"\)\]/);
  assert.match(source, /\[switch\]\$FetchOfficialRoots/);
  assert.match(source, /\[switch\]\$KeepWindowOpen/);
  assert.match(source, /function Get-OfficialPostgresRootBundle/);
  assert.match(source, /Invoke-WebRequest[\s\S]+-OutFile/);
  assert.match(source, /\.partial\.\*/);
  assert.match(source, /Move-Item -LiteralPath \$bundlePartial/);
  assert.match(source, /Get-Content -LiteralPath \$x1Partial -Raw -Encoding ASCII/);
  assert.match(source, /Get-Content -LiteralPath \$x2Partial -Raw -Encoding ASCII/);
  assert.doesNotMatch(source, /\.Content\.Trim/);
  assert.match(source, /Write-Host "Backup fehlgeschlagen:"/);
  assert.match(source, /try \{ Write-Diagnostic \$safeFailure \} catch/);
  assert.match(source, /if \(\$KeepWindowOpen\) \{ \[void\]\(Read-Host/);
  assert.doesNotMatch(source, /Write-Error/);
  assert.match(source, /PGCHANNELBINDING/);
  assert.match(source, /\$script:ChannelBinding = if \(\$Provider -eq "Neon"\) \{ "require" \}/);
  assert.match(source, /function Assert-ProviderConnection/);
  assert.match(source, /Neon-Backups duerfen keinen Pooler-Endpunkt verwenden/);
  assert.match(source, /separate psql probe skipped to avoid a second prompt/);
  assert.match(source, /certutil\.exe -dump/);
  assert.match(source, /function Assert-Manifest/);
  assert.match(source, /Assert-Manifest \$dumpPath/);
  assert.match(source, /--single-transaction/);
  assert.match(source, /function Compare-RestoredDatabase/);
  assert.match(source, /function Get-TableFingerprint/);
  assert.match(source, /function Get-SchemaObjectInventory/);
  assert.match(source, /function Compare-SchemaObjects/);
  assert.match(source, /pg_catalog\.pg_sequences/);
  assert.match(source, /pg_catalog\.pg_indexes/);
  assert.match(source, /pg_catalog\.pg_constraint/);
  assert.match(source, /pg_get_constraintdef/);
  assert.match(source, /\[string\]\$TargetHostName/);
  assert.match(source, /\[int\]\$TargetPort/);
  assert.match(source, /\[string\]\$TargetUser/);
  assert.match(source, /digest\([^\n]+sha256/);
  assert.match(restoreValidator, /PGSSLMODE = "verify-full"/);
  assert.match(restoreValidator, /PGCHANNELBINDING = "require"/);
  assert.match(restoreValidator, /Read-Host -AsSecureString/);
  assert.match(restoreValidator, /\[Console\]::Error\.Write\('Neon-Produktionskopie Passwort: '\)/);
  assert.match(restoreValidator, /\[Console\]::Error\.Write\('Isoliertes Restore-Ziel Passwort: '\)/);
  assert.match(restoreValidator, /SecureStringToBSTR/);
  assert.match(restoreValidator, /ZeroFreeBSTR/);
  assert.doesNotMatch(restoreValidator, /setRawMode/);
  assert.doesNotMatch(restoreValidator, /process\.stdin\.on/);
  assert.match(restoreValidator, /--single-transaction/);
  assert.match(restoreValidator, /pg_catalog\.pg_sequences/);
  assert.match(restoreValidator, /pg_catalog\.pg_indexes/);
  assert.match(restoreValidator, /pg_catalog\.pg_constraint/);
  assert.doesNotMatch(restoreValidator, /--clean/);
  assert.doesNotMatch(restoreValidator, /DROP DATABASE/);
});
