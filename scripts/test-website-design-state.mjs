import assert from "node:assert/strict";
import {initialDesignState,transitionDesign} from "../src/website-design-state.js";
const initial=initialDesignState();
const context={ownerId:"owner"};
const apply=(s,type,extra={})=>transitionDesign(s,{type,expectedRevision:s.revision,...extra},context);
const saved=apply(initial,"save",{design:{shade:30}}).state;
assert.equal(saved.revision,1);
assert.equal(saved.published,null);
assert.equal(initial.draft.shade,65);
const live=apply(saved,"publish").state;
assert.equal(live.published.design.shade,30);
assert.equal(live.history.length,1);
const edited=apply(live,"save",{design:{shade:80}}).state;
assert.equal(edited.published.design.shade,30);
assert.equal(edited.draft.shade,80);
assert.equal(apply(edited,"save",{expectedRevision:1,design:{}}).error,"REVISION_CONFLICT");
const live2=apply(edited,"publish").state;
const restored=apply(live2,"restore",{sourceRevision:2}).state;
assert.equal(restored.draft.shade,30);
assert.equal(restored.published.design.shade,80);
assert.equal(restored.history.length,2);
assert.equal(apply(restored,"restore",{sourceRevision:999}).error,"VERSION_NOT_FOUND");
assert.equal(apply(restored,"save",{design:{shade:99}}).ok,false);
assert.equal(apply(restored,"unknown").ok,false);
const id="12345678-1234-1234-1234-123456789abc";
const asset={id,accountId:"owner",mimeType:"image/png",validated:true,deleted:false,publicApproved:false};
const mediaDraft=transitionDesign(initial,{type:"save",expectedRevision:0,design:{backgroundAssetId:id}},{ownerId:"owner",asset}).state;
assert.equal(transitionDesign(mediaDraft,{type:"publish",expectedRevision:1},{ownerId:"owner",asset}).error,"MEDIA_NOT_APPROVED");
assert.equal(transitionDesign(mediaDraft,{type:"publish",expectedRevision:1},{ownerId:"owner",asset:{...asset,publicApproved:true}}).ok,true);
assert.equal(apply(mediaDraft,"publish").ok,false);
assert.equal(apply({...initial,revision:Number.MAX_SAFE_INTEGER},"save",{design:{}}).error,"REVISION_EXHAUSTED");
console.log("Website design state passed");
