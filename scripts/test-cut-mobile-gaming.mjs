import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const js=fs.readFileSync(new URL('../assets/js/cut-mobile-gaming.js',import.meta.url),'utf8');
const context={module:{exports:{}}};vm.runInNewContext(js,context);
const {plan,timelinePlan,inspectOutput,rectangle,mime}=context.module.exports;
const p=plan({duration:55,start:5,end:35,format:'vertical',resolution:1080,fps:60,rate:20});
assert.equal(p.width,1080);assert.equal(p.height,1920);assert.equal(p.fps,60);assert.equal(p.rate,20);
assert.equal(plan({duration:30,start:0,end:30,format:'landscape',resolution:720}).width,1280);
assert.equal(plan({duration:30,start:0,end:30,format:'square'}).height,1080);
for(const [start,end] of [[-1,10],[2,1],[0,56],[3,3.1]])assert.throws(()=>plan({duration:55,start,end}),/Schnittbereich/);
assert.throws(()=>plan({duration:200,start:0,end:181}),/Schnittbereich/);
const r=rectangle(1920,1080,1080,1920);assert.equal(r[2],1080);assert.equal(r[3],607.5);
assert.equal(rectangle(1920,1080,1080,1920,true)[3],1920);
assert.equal(mime({isTypeSupported:t=>t==='video/mp4'}),'video/mp4');
assert.equal(mime({isTypeSupported:t=>t==='video/webm'}),'video/webm');
assert.equal(mime({isTypeSupported:()=>false}),'');
const opts={duration:100,start:0,end:20,format:'vertical',resolution:1080,fps:30,rate:16};
const reel=timelinePlan(opts,[{start:40,end:50},{start:5,end:20}]);
assert.equal(reel.total,25);assert.equal(reel.segments[0].start,40);assert.equal(reel.segments[1].start,5);
assert.equal(timelinePlan(opts).total,20);
assert.throws(()=>timelinePlan({...opts,duration:200},[{start:0,end:100},{start:10,end:100}]),/180/);
assert.throws(()=>timelinePlan(opts,Array.from({length:13},()=>({start:0,end:1}))),/12/);
assert.throws(()=>timelinePlan(opts,[{start:99,end:101}]),/Schnittbereich/);
assert.equal(inspectOutput({width:1080,height:1920,duration:25.1},reel).ok,true);
assert.equal(inspectOutput({width:720,height:1280,duration:25},reel).ok,false);
assert.equal(inspectOutput({width:1080,height:1920,duration:30},reel).ok,false);
assert.equal(inspectOutput({width:1080,height:1920,duration:Infinity},reel).ok,false);
const html=fs.readFileSync(new URL('../pages/cut-studio.html',import.meta.url),'utf8');
assert.match(html,/id="cutMobileGaming"/);assert.match(html,/cut-mobile-gaming\.js/);assert.match(html,/cut-mobile-gaming\.css/);
assert.match(html,/id="queueCutExport"/);assert.match(html,/id="cutLocalVideo"/);
console.log('Mobile gaming planning and integration contracts passed.');
