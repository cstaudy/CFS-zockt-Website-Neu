import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {launcherOnline,launcherEvidence,readCreatorEvidence,providerEvidence,streamReadiness,technicalStatus} from "../src/creator-status-evidence.js";
const now=Date.parse("2026-11-28T12:00:00Z"), fresh={status:"active",last_seen_at:new Date(now-1000),obs_connected:true,machine_name:"CI PC",client_version:"test"},old={...fresh,last_seen_at:new Date(now-120000)};
assert.equal(launcherOnline(fresh,now),true);
for(const row of [old,{...fresh,last_seen_at:new Date(now+1)},{...fresh,last_seen_at:null},{...fresh,last_seen_at:"invalid"},{...fresh,status:"revoked"}])assert.equal(launcherOnline(row,now),false);
assert.deepEqual(launcherEvidence([],now),{paired:false,online:false,obs_connected:false,status:"not_paired",device:null});
assert.equal(launcherEvidence([old],now).status,"offline");
assert.equal(launcherEvidence([old],now).obs_connected,false);
assert.equal(launcherEvidence([old,{...fresh,obs_connected:false}],now).status,"launcher_only");
assert.equal(launcherEvidence([old,fresh],now).status,"obs_reported");
const calls=[],configured={tiktok:true,twitch:true,bridge:true};
const db={async query(sql,values){calls.push({sql,values});return {rows:sql.includes("tiktok_connections")?[{provider:"tiktok",scope:"user.info.basic",expires_at:new Date(now+10000)}]:[old]};}};
const e=await readCreatorEvidence(db,"ci-account",configured,now);
assert(calls.every(c=>c.values.length===1&&c.values[0]==="ci-account"));
assert(calls.every(c=>/^select /i.test(c.sql)));
assert.equal(providerEvidence(e.platforms.find(p=>p.provider==="tiktok")),"record_present_unverified");
assert.equal(providerEvidence(e.platforms.find(p=>p.provider==="twitch")),"not_connected");
const stream=streamReadiness(e,configured);
assert.equal(stream.ready,false);assert.deepEqual(stream.checks,{twitch:false,tiktok:false,launcher:false,obs:false});
const status=technicalStatus(e,configured,now);
assert.equal(status.overall,"partial");assert.equal(status.components.launcher.state,"stale");
assert.equal(status.components.live.state,"unknown");assert.equal(status.components.release.state,"unknown");
const unavailable=await readCreatorEvidence({async query(){throw Error("database unavailable");}},"ci-account",configured,now);
assert.deepEqual(unavailable,{platforms:null,launcher:null});
assert.equal(streamReadiness(unavailable,configured).evidence.launcher,"unknown");
assert.equal(technicalStatus(unavailable,configured,now).components.launcher.state,"unknown");
assert.equal(streamReadiness({...e,launcher:launcherEvidence([fresh],now)},configured).ready,false);
assert.equal(providerEvidence({configured:true,connection:"record_present",token_status:"expired"}),"expired");
assert.equal(providerEvidence({configured:false}),"not_configured");
const server=await readFile(new URL("../server.js",import.meta.url),"utf8");
assert(server.includes("local_ready:false,production_release_approved:false"));
assert(server.includes("connected:evidence.online,paired:evidence.paired"));
const dashboard=await readFile(new URL("../assets/js/page-dashboard.js",import.meta.url),"utf8");
assert(!dashboard.includes("connection.obs = liveWidgets.length > 0"));
assert(!dashboard.includes("follower_count || 0"));
const system=await readFile(new URL("../assets/js/page-system-check.js",import.meta.url),"utf8");
assert(!system.includes("data.release?.local_ready===true||data.ok===true"));
console.log("Creator status evidence: fresh heartbeat, stale and future timestamps, account-bound metadata, unknown states, no inferred live or release readiness.");
